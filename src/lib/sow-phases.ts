const STOP_WORDS = new Set([
  "THE",
  "AND",
  "FOR",
  "WITH",
  "W",
  "NO",
  "OF",
  "ALT",
  "BASE",
  "ONLY",
  "UNSPECIFIED",
  "SIZE",
  "ALLISON",
]);

/** Normalize SOW / catalog product names for fuzzy comparison. */
export function normalizeSowText(raw: string): string {
  return raw
    .toUpperCase()
    .replace(/[""″''′]/g, "")
    .replace(/(\d)\s*[×X]\s*(\d)/g, "$1 X $2")
    .replace(/×/g, "X")
    .replace(/W\//g, "W ")
    .replace(/[^A-Z0-9.\s-]/g, " ")
    .replace(/\b(BH|SH|DIAMETER)\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function significantTokens(normalized: string): string[] {
  return normalized
    .split(" ")
    .map((t) => t.replace(/^-+|-+$/g, ""))
    .filter((t) => t.length > 1 && !STOP_WORDS.has(t));
}

/**
 * Fuzzy/partial match: SOW name ↔ catalog original_name.
 * Handles quote/inch variance, X separators, BH/SH suffixes, and soft token overlap.
 */
export function catalogNameMatchesSow(
  catalogName: string,
  sowName: string,
): boolean {
  const catalog = normalizeSowText(catalogName);
  const sow = normalizeSowText(sowName);
  if (!catalog || !sow) return false;
  if (catalog === sow) return true;
  if (catalog.includes(sow) || sow.includes(catalog)) return true;

  const sowNums = [...new Set(sow.match(/\d+/g) ?? [])];
  const catalogNums = new Set(catalog.match(/\d+/g) ?? []);
  if (sowNums.length > 0 && !sowNums.every((n) => catalogNums.has(n))) {
    // Allow vague SOW rows without dims (e.g. "BRAVADA COFFEE TABLE (unspecified size)")
    const sowHasDims = /\d/.test(sowName);
    if (sowHasDims) return false;
  }

  const sowTokens = significantTokens(sow);
  if (sowTokens.length === 0) return false;
  const catalogTokens = significantTokens(catalog);
  const catalogSet = new Set(catalogTokens);

  let hits = 0;
  for (const token of sowTokens) {
    if (/^\d+$/.test(token)) {
      if (catalogNums.has(token)) hits += 1;
      continue;
    }
    if (
      catalogSet.has(token) ||
      catalogTokens.some(
        (c) => c.includes(token) || token.includes(c),
      )
    ) {
      hits += 1;
    }
  }

  const ratio = hits / sowTokens.length;
  // Prefer high overlap; looser when SOW has few tokens (e.g. "Ripple Table")
  return sowTokens.length <= 2 ? ratio >= 1 : ratio >= 0.75;
}

export function matchesSowPhase(
  catalogName: string,
  phaseNames: readonly string[],
): boolean {
  return phaseNames.some((sow) => catalogNameMatchesSow(catalogName, sow));
}

export type SowWorkflowFilter = "phase1" | "phase2" | "auto3d";

/** Compose SOW phase + optional 3D-auto flag against a dictionary row. */
export function rowMatchesWorkflowFilters(
  row: {
    originalName: string;
    hasAutoGeneratedDraft?: boolean;
  },
  active: ReadonlySet<SowWorkflowFilter>,
): boolean {
  if (active.size === 0) return true;

  const wantPhase1 = active.has("phase1");
  const wantPhase2 = active.has("phase2");
  const wantAuto = active.has("auto3d");

  if (wantPhase1 || wantPhase2) {
    const inPhase =
      (wantPhase1 && matchesSowPhase(row.originalName, SOW_PHASE_1)) ||
      (wantPhase2 && matchesSowPhase(row.originalName, SOW_PHASE_2));
    if (!inPhase) return false;
  }

  if (wantAuto && !row.hasAutoGeneratedDraft) {
    return false;
  }

  return true;
}
